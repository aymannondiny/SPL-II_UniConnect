CREATE TABLE content_reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES users(user_id),
    target_type VARCHAR(30) NOT NULL CHECK (target_type IN ('USER','CLUB','ANNOUNCEMENT','EVENT','CHAT_MESSAGE')),
    target_id BIGINT NOT NULL CHECK (target_id > 0),
    reason VARCHAR(1000) NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('SUBMITTED','UNDER_REVIEW','ACTION_TAKEN','NO_ACTION')),
    target_label VARCHAR(500) NOT NULL,
    target_snapshot TEXT NOT NULL,
    target_owner_user_id BIGINT REFERENCES users(user_id),
    parent_club_id BIGINT REFERENCES clubs(club_id),
    reviewer_id BIGINT REFERENCES users(user_id),
    submitted_at TIMESTAMP NOT NULL,
    review_started_at TIMESTAMP,
    resolved_at TIMESTAMP,
    resolution_summary VARCHAR(1000),
    internal_notes VARCHAR(2000),
    open_reporter_id BIGINT REFERENCES users(user_id),
    open_target_type VARCHAR(30),
    open_target_id BIGINT,
    CONSTRAINT unique_open_report UNIQUE (open_reporter_id, open_target_type, open_target_id),
    CONSTRAINT report_open_key_shape CHECK (
        (status IN ('SUBMITTED','UNDER_REVIEW') AND open_reporter_id=reporter_id
            AND open_target_type=target_type AND open_target_id=target_id)
        OR (status IN ('ACTION_TAKEN','NO_ACTION') AND open_reporter_id IS NULL
            AND open_target_type IS NULL AND open_target_id IS NULL)
    ),
    CONSTRAINT report_review_shape CHECK (
        (status='SUBMITTED' AND reviewer_id IS NULL AND review_started_at IS NULL
            AND resolved_at IS NULL AND resolution_summary IS NULL AND internal_notes IS NULL)
        OR (status='UNDER_REVIEW' AND reviewer_id IS NOT NULL AND review_started_at IS NOT NULL
            AND resolved_at IS NULL AND resolution_summary IS NULL)
        OR (status IN ('ACTION_TAKEN','NO_ACTION') AND reviewer_id IS NOT NULL
            AND review_started_at IS NOT NULL AND resolved_at IS NOT NULL
            AND resolution_summary IS NOT NULL)
    )
);

CREATE INDEX idx_reports_reporter ON content_reports(reporter_id, report_id);
CREATE INDEX idx_reports_queue ON content_reports(status, report_id);
CREATE INDEX idx_reports_target ON content_reports(target_type, target_id, report_id);

CREATE TABLE report_audit_logs (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES content_reports(report_id),
    actor_id BIGINT NOT NULL REFERENCES users(user_id),
    event_type VARCHAR(30) NOT NULL CHECK (event_type IN ('SUBMITTED','UNDER_REVIEW','ACTION_TAKEN','NO_ACTION')),
    previous_status VARCHAR(30) CHECK (previous_status IS NULL OR previous_status IN ('SUBMITTED','UNDER_REVIEW','ACTION_TAKEN','NO_ACTION')),
    new_status VARCHAR(30) NOT NULL CHECK (new_status IN ('SUBMITTED','UNDER_REVIEW','ACTION_TAKEN','NO_ACTION')),
    internal_note VARCHAR(2000),
    occurred_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_report_audit_history ON report_audit_logs(report_id, audit_id);

CREATE TABLE report_action_links (
    link_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL UNIQUE REFERENCES content_reports(report_id),
    evidence_source VARCHAR(30) NOT NULL CHECK (evidence_source IN ('ACCOUNT_MODERATION','CLUB_LIFECYCLE','PUBLICATION')),
    evidence_id BIGINT NOT NULL,
    action_type VARCHAR(50) NOT NULL,
    subject_type VARCHAR(30) NOT NULL CHECK (subject_type IN ('USER','CLUB','ANNOUNCEMENT','EVENT')),
    subject_id BIGINT NOT NULL,
    action_occurred_at TIMESTAMP NOT NULL,
    linked_by BIGINT NOT NULL REFERENCES users(user_id),
    linked_at TIMESTAMP NOT NULL,
    CONSTRAINT unique_action_evidence UNIQUE (evidence_source, evidence_id, report_id)
);

ALTER TABLE notifications DROP CONSTRAINT notification_type_allowed;
ALTER TABLE notifications DROP CONSTRAINT notification_reference_allowed;
ALTER TABLE notifications ADD CONSTRAINT notification_type_allowed CHECK (
    type IN ('CONNECTION_REQUESTED','CONNECTION_ACCEPTED','CLUB_ROLE_GRANTED','CLUB_ROLE_REVOKED',
             'PUBLISHING_SUSPENDED','PUBLISHING_RESTORED','ACCOUNT_SUSPENDED','ACCOUNT_REACTIVATED',
             'REPORT_RESOLVED')
);
ALTER TABLE notifications ADD CONSTRAINT notification_reference_allowed CHECK (
    (type IN ('CONNECTION_REQUESTED','CONNECTION_ACCEPTED') AND reference_type='CONNECTION') OR
    (type IN ('CLUB_ROLE_GRANTED','CLUB_ROLE_REVOKED','PUBLISHING_SUSPENDED','PUBLISHING_RESTORED') AND reference_type='CLUB') OR
    (type IN ('ACCOUNT_SUSPENDED','ACCOUNT_REACTIVATED') AND reference_type='USER') OR
    (type='REPORT_RESOLVED' AND reference_type='REPORT')
);
