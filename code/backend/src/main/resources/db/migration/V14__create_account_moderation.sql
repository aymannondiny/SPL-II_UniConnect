CREATE TABLE moderation_actions (
    action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL REFERENCES users(user_id),
    target_user_id BIGINT NOT NULL REFERENCES users(user_id),
    action_type VARCHAR(40) NOT NULL CHECK (action_type IN ('SUSPEND_ACCOUNT','REACTIVATE_ACCOUNT')),
    reason VARCHAR(1000) NOT NULL,
    previous_state VARCHAR(50) NOT NULL,
    new_state VARCHAR(50) NOT NULL,
    reversal_of_action_id BIGINT UNIQUE REFERENCES moderation_actions(action_id),
    created_at TIMESTAMP NOT NULL,
    reversed_at TIMESTAMP,
    CONSTRAINT moderation_account_transition CHECK (
        (action_type='SUSPEND_ACCOUNT' AND previous_state='ACTIVE' AND new_state='SUSPENDED') OR
        (action_type='REACTIVATE_ACCOUNT' AND previous_state='SUSPENDED' AND new_state='ACTIVE')
    ),
    CONSTRAINT moderation_reversal_time CHECK (reversed_at IS NULL OR reversed_at >= created_at)
);

CREATE INDEX idx_moderation_actions_target ON moderation_actions(target_user_id, action_id);

CREATE TABLE audit_logs (
    audit_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moderation_action_id BIGINT NOT NULL UNIQUE REFERENCES moderation_actions(action_id),
    actor_id BIGINT NOT NULL REFERENCES users(user_id),
    event_type VARCHAR(50) NOT NULL CHECK (event_type IN ('ACCOUNT_SUSPENDED','ACCOUNT_REACTIVATED')),
    subject_type VARCHAR(30) NOT NULL CHECK (subject_type='USER'),
    subject_id BIGINT NOT NULL REFERENCES users(user_id),
    reason VARCHAR(1000) NOT NULL,
    previous_state_json VARCHAR(1000) NOT NULL,
    new_state_json VARCHAR(1000) NOT NULL,
    occurred_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_audit_logs_subject ON audit_logs(subject_type, subject_id, audit_log_id);

ALTER TABLE notifications DROP CONSTRAINT notification_type_allowed;
ALTER TABLE notifications DROP CONSTRAINT notification_reference_allowed;
ALTER TABLE notifications ADD CONSTRAINT notification_type_allowed CHECK (
    type IN ('CONNECTION_REQUESTED','CONNECTION_ACCEPTED','CLUB_ROLE_GRANTED','CLUB_ROLE_REVOKED',
             'PUBLISHING_SUSPENDED','PUBLISHING_RESTORED','ACCOUNT_SUSPENDED','ACCOUNT_REACTIVATED')
);
ALTER TABLE notifications ADD CONSTRAINT notification_reference_allowed CHECK (
    (type IN ('CONNECTION_REQUESTED','CONNECTION_ACCEPTED') AND reference_type='CONNECTION') OR
    (type IN ('CLUB_ROLE_GRANTED','CLUB_ROLE_REVOKED','PUBLISHING_SUSPENDED','PUBLISHING_RESTORED') AND reference_type='CLUB') OR
    (type IN ('ACCOUNT_SUSPENDED','ACCOUNT_REACTIVATED') AND reference_type='USER')
);
