CREATE TABLE teammate_projects (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_user_id BIGINT NOT NULL REFERENCES users(user_id),
    title VARCHAR(200) NOT NULL,
    description VARCHAR(5000) NOT NULL,
    team_size_limit INTEGER NOT NULL CHECK (team_size_limit >= 2 AND team_size_limit <= 100),
    duration VARCHAR(200),
    course_name VARCHAR(200),
    application_deadline DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN','CLOSED','DELETED')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    closed_at TIMESTAMP,
    deleted_at TIMESTAMP,
    creator_redacted_at TIMESTAMP,
    CONSTRAINT teammate_project_state CHECK (
        (status='OPEN' AND closed_at IS NULL AND deleted_at IS NULL)
        OR (status='CLOSED' AND closed_at IS NOT NULL AND deleted_at IS NULL)
        OR (status='DELETED' AND deleted_at IS NOT NULL)
    )
);

CREATE INDEX idx_teammate_projects_browse
    ON teammate_projects(status, application_deadline, created_at, project_id);
CREATE INDEX idx_teammate_projects_creator
    ON teammate_projects(creator_user_id, project_id);

CREATE TABLE teammate_project_skills (
    project_id BIGINT NOT NULL REFERENCES teammate_projects(project_id),
    skill_id BIGINT NOT NULL REFERENCES skills(skill_id),
    required BOOLEAN NOT NULL,
    PRIMARY KEY (project_id, skill_id)
);
CREATE INDEX idx_teammate_project_skills_skill
    ON teammate_project_skills(skill_id, project_id);

CREATE TABLE teammate_project_memberships (
    membership_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES teammate_projects(project_id),
    member_user_id BIGINT NOT NULL REFERENCES users(user_id),
    role VARCHAR(20) NOT NULL CHECK (role IN ('CREATOR','TEAMMATE')),
    creator_project_id BIGINT UNIQUE REFERENCES teammate_projects(project_id),
    joined_at TIMESTAMP NOT NULL,
    CONSTRAINT unique_teammate_project_member UNIQUE (project_id, member_user_id),
    CONSTRAINT teammate_creator_key CHECK (
        (role='CREATOR' AND creator_project_id=project_id)
        OR (role='TEAMMATE' AND creator_project_id IS NULL)
    )
);
CREATE INDEX idx_teammate_memberships_member
    ON teammate_project_memberships(member_user_id, project_id);

CREATE TABLE teammate_project_applications (
    application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES teammate_projects(project_id),
    applicant_user_id BIGINT NOT NULL REFERENCES users(user_id),
    message VARCHAR(500),
    status VARCHAR(30) NOT NULL CHECK (status IN ('PENDING','ACCEPTED','REJECTED','CANCELLED_PROJECT_DELETED')),
    applied_at TIMESTAMP NOT NULL,
    responded_at TIMESTAMP,
    CONSTRAINT unique_teammate_project_application UNIQUE (project_id, applicant_user_id),
    CONSTRAINT teammate_application_response CHECK (
        (status='PENDING' AND responded_at IS NULL)
        OR (status<>'PENDING' AND responded_at IS NOT NULL)
    )
);
CREATE INDEX idx_teammate_applications_project
    ON teammate_project_applications(project_id, status, application_id);
CREATE INDEX idx_teammate_applications_applicant
    ON teammate_project_applications(applicant_user_id, application_id);

CREATE TABLE teammate_project_audits (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES teammate_projects(project_id),
    actor_user_id BIGINT REFERENCES users(user_id),
    application_id BIGINT REFERENCES teammate_project_applications(application_id),
    event_type VARCHAR(40) NOT NULL CHECK (event_type IN (
        'CREATED','UPDATED','CLOSED','REOPENED','DELETED','OWNER_ANONYMIZED',
        'APPLICATION_SUBMITTED','APPLICATION_ACCEPTED','APPLICATION_REJECTED','APPLICATION_CANCELLED'
    )),
    occurred_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_teammate_project_audits
    ON teammate_project_audits(project_id, audit_id);

