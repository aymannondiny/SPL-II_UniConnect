             'PUBLISHING_SUSPENDED','PUBLISHING_RESTORED','NEW_MESSAGE',
             'ACCOUNT_SUSPENDED','ACCOUNT_REACTIVATED','REPORT_RESOLVED',
             'PROJECT_APPLICATION_ACCEPTED','PROJECT_APPLICATION_REJECTED','PROJECT_DELETED')
);
ALTER TABLE notifications ADD CONSTRAINT notification_reference_allowed CHECK (
    (type IN ('CONNECTION_REQUESTED','CONNECTION_ACCEPTED') AND reference_type='CONNECTION') OR
    (type IN ('CLUB_ROLE_GRANTED','CLUB_ROLE_REVOKED','PUBLISHING_SUSPENDED','PUBLISHING_RESTORED') AND reference_type='CLUB') OR
    (type='NEW_MESSAGE' AND reference_type='CONVERSATION') OR
    (type IN ('ACCOUNT_SUSPENDED','ACCOUNT_REACTIVATED') AND reference_type='USER') OR
    (type='REPORT_RESOLVED' AND reference_type='REPORT') OR
    (type IN ('PROJECT_APPLICATION_ACCEPTED','PROJECT_APPLICATION_REJECTED','PROJECT_DELETED')
        AND reference_type='PROJECT')
);
