-- V12 adds club publications after V11 peer mentorship.
-- V11 is reserved for club publications. Mentorship must rebase after this migration.
ALTER TABLE club_role_assignments ADD CONSTRAINT club_assignment_identity UNIQUE (assignment_id,club_id,user_id);
CREATE TABLE club_announcements (
    announcement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL REFERENCES clubs(club_id),
    author_user_id BIGINT NOT NULL REFERENCES users(user_id),
    author_assignment_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    content VARCHAR(10000) NOT NULL,
    priority VARCHAR(20) NOT NULL CHECK (priority IN ('NORMAL','IMPORTANT','URGENT')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('UNPUBLISHED','PUBLISHED','REMOVED')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    published_at TIMESTAMP,
    expires_at TIMESTAMP,
    removed_at TIMESTAMP,
    CONSTRAINT announcement_author_assignment FOREIGN KEY (author_assignment_id,club_id,author_user_id)
        REFERENCES club_role_assignments(assignment_id,club_id,user_id),
    CONSTRAINT announcement_identity UNIQUE (announcement_id,club_id),
    CONSTRAINT announcement_published_shape CHECK (status<>'PUBLISHED' OR published_at IS NOT NULL),
    CONSTRAINT announcement_removed_shape CHECK ((status='REMOVED' AND removed_at IS NOT NULL) OR (status<>'REMOVED' AND removed_at IS NULL))
);
CREATE INDEX idx_announcement_feed ON club_announcements(status,published_at,announcement_id);
CREATE INDEX idx_announcement_club ON club_announcements(club_id,created_at,announcement_id);
CREATE INDEX idx_announcement_author ON club_announcements(author_assignment_id,announcement_id);
CREATE TABLE club_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL REFERENCES clubs(club_id),
    author_user_id BIGINT NOT NULL REFERENCES users(user_id),
    author_assignment_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(10000) NOT NULL,
    location VARCHAR(500),
    registration_url VARCHAR(2048),
    registration_deadline TIMESTAMP,
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PUBLISHED','REMOVED')),
    published_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    removed_at TIMESTAMP,
    CONSTRAINT event_author_assignment FOREIGN KEY (author_assignment_id,club_id,author_user_id)
        REFERENCES club_role_assignments(assignment_id,club_id,user_id),
    CONSTRAINT event_identity UNIQUE (event_id,club_id),
    CONSTRAINT event_time_order CHECK (ends_at>starts_at),
    CONSTRAINT event_registration_deadline CHECK (registration_deadline IS NULL OR registration_deadline<=starts_at),
    CONSTRAINT event_removed_shape CHECK ((status='REMOVED' AND removed_at IS NOT NULL) OR (status<>'REMOVED' AND removed_at IS NULL))
);
CREATE INDEX idx_event_current ON club_events(status,ends_at,starts_at,event_id);
CREATE INDEX idx_event_history ON club_events(club_id,status,ends_at,event_id);
CREATE INDEX idx_event_author ON club_events(author_assignment_id,event_id);
CREATE TABLE club_publication_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL REFERENCES clubs(club_id),
    announcement_id BIGINT,
    event_id BIGINT,
    actor_user_id BIGINT NOT NULL REFERENCES users(user_id),
    actor_assignment_id BIGINT NOT NULL,
    action VARCHAR(20) NOT NULL CHECK (action IN ('CREATED','EDITED','PUBLISHED','UNPUBLISHED','REMOVED')),
    reason VARCHAR(1000),
    before_snapshot TEXT,
    after_snapshot TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT publication_audit_actor FOREIGN KEY (actor_assignment_id,club_id,actor_user_id)
        REFERENCES club_role_assignments(assignment_id,club_id,user_id),
    CONSTRAINT publication_audit_announcement FOREIGN KEY (announcement_id,club_id) REFERENCES club_announcements(announcement_id,club_id),
    CONSTRAINT publication_audit_event FOREIGN KEY (event_id,club_id) REFERENCES club_events(event_id,club_id),
    CONSTRAINT publication_audit_target CHECK ((announcement_id IS NOT NULL AND event_id IS NULL) OR (announcement_id IS NULL AND event_id IS NOT NULL)),
    CONSTRAINT publication_audit_reason CHECK (action NOT IN ('UNPUBLISHED','REMOVED') OR (reason IS NOT NULL AND CHAR_LENGTH(TRIM(reason))>0))
);
CREATE INDEX idx_publication_audit_club ON club_publication_audit(club_id,audit_id);
