CREATE TABLE mentor_profiles (
    mentor_profile_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    mentoring_bio VARCHAR(5000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE', 'UNAVAILABLE')),
    registered_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_mentor_profiles_user ON mentor_profiles(user_id);
CREATE INDEX idx_mentor_profiles_status ON mentor_profiles(status);

CREATE TABLE mentor_expertise (
    expertise_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_profile_id BIGINT NOT NULL REFERENCES mentor_profiles(mentor_profile_id) ON DELETE CASCADE,
    topic VARCHAR(100) NOT NULL,
    description VARCHAR(1000)
);
CREATE INDEX idx_mentor_expertise_profile ON mentor_expertise(mentor_profile_id);
CREATE INDEX idx_mentor_expertise_topic ON mentor_expertise(topic);

CREATE TABLE mentorship_slots (
    slot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_profile_id BIGINT NOT NULL REFERENCES mentor_profiles(mentor_profile_id) ON DELETE CASCADE,
    topic VARCHAR(200) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    schedule_type VARCHAR(20) NOT NULL CHECK (schedule_type IN ('ONE_TIME', 'WEEKLY', 'BIWEEKLY')),
    start_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    recurrence_end_date DATE,
    mode VARCHAR(20) NOT NULL CHECK (mode IN ('IN_PERSON', 'ONLINE')),
    location VARCHAR(255),
    meeting_link VARCHAR(500),
    capacity INTEGER NOT NULL CHECK (capacity BETWEEN 7 AND 10),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED', 'CANCELLED')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT valid_slot_time CHECK (end_time > start_time),
    CONSTRAINT valid_slot_date CHECK (recurrence_end_date IS NULL OR recurrence_end_date >= start_date)
);
CREATE INDEX idx_mentorship_slots_mentor ON mentorship_slots(mentor_profile_id);
CREATE INDEX idx_mentorship_slots_status ON mentorship_slots(status);

CREATE TABLE mentorship_occurrences (
    occurrence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id BIGINT NOT NULL REFERENCES mentorship_slots(slot_id) ON DELETE CASCADE,
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    cancelled_at TIMESTAMP
);
CREATE INDEX idx_mentorship_occurrences_slot ON mentorship_occurrences(slot_id);

CREATE TABLE mentorship_enrollments (
    enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id BIGINT NOT NULL REFERENCES mentorship_slots(slot_id) ON DELETE CASCADE,
    mentee_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    join_message VARCHAR(300),
    learning_goal VARCHAR(1000),
    joined_at TIMESTAMP NOT NULL,
    left_at TIMESTAMP,
    UNIQUE (slot_id, mentee_id)
);
CREATE INDEX idx_mentorship_enrollments_slot ON mentorship_enrollments(slot_id);
CREATE INDEX idx_mentorship_enrollments_mentee ON mentorship_enrollments(mentee_id);
