CREATE TABLE club_creation_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_user_id BIGINT NOT NULL REFERENCES users(user_id),
    club_name VARCHAR(150) NOT NULL,
    name_key VARCHAR(150) NOT NULL,
    category VARCHAR(100) NOT NULL,
    description VARCHAR(5000) NOT NULL,
    logo_url VARCHAR(2048),
    contact_email VARCHAR(320),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','APPROVED','REJECTED')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    decided_at TIMESTAMP,
    decided_by BIGINT REFERENCES users(user_id),
    rejection_reason VARCHAR(1000),
    club_id BIGINT UNIQUE REFERENCES clubs(club_id),
    CONSTRAINT club_request_decision_shape CHECK (
        (status='PENDING' AND decided_at IS NULL AND decided_by IS NULL AND rejection_reason IS NULL AND club_id IS NULL)
        OR (status='APPROVED' AND decided_at IS NOT NULL AND decided_by IS NOT NULL AND club_id IS NOT NULL AND rejection_reason IS NULL)
        OR (status='REJECTED' AND decided_at IS NOT NULL AND decided_by IS NOT NULL AND club_id IS NULL)
    )
);
CREATE INDEX idx_club_request_owner ON club_creation_requests(requester_user_id,created_at DESC);
CREATE INDEX idx_club_request_review ON club_creation_requests(status,created_at,request_id);
