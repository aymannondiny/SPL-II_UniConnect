CREATE TABLE clubs (
    club_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_name VARCHAR(150) NOT NULL,
    name_key VARCHAR(150) NOT NULL UNIQUE,
    category VARCHAR(100) NOT NULL,
    description VARCHAR(5000) NOT NULL,
    logo_url VARCHAR(2048),
    contact_email VARCHAR(320),
    status VARCHAR(30) NOT NULL CHECK (status IN ('ACTIVE','PUBLISHING_SUSPENDED','REMOVED')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE TABLE club_role_assignments (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL REFERENCES clubs(club_id),
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    role VARCHAR(30) NOT NULL CHECK (role IN ('CLUB_ADMINISTRATOR','REPRESENTATIVE')),
    assigned_by BIGINT NOT NULL REFERENCES users(user_id),
    assigned_at TIMESTAMP NOT NULL,
    revoked_by BIGINT REFERENCES users(user_id),
    revoked_at TIMESTAMP,
    current_club_id BIGINT,
    current_user_id BIGINT,
    administrator_club_id BIGINT UNIQUE,
    administrator_user_id BIGINT UNIQUE,
    CONSTRAINT club_current_member_unique UNIQUE (current_club_id,current_user_id),
    CONSTRAINT club_assignment_keys CHECK (
        (revoked_at IS NOT NULL AND revoked_by IS NOT NULL AND current_club_id IS NULL AND current_user_id IS NULL AND administrator_club_id IS NULL AND administrator_user_id IS NULL)
        OR (revoked_at IS NULL AND revoked_by IS NULL AND current_club_id IS NOT NULL AND current_user_id IS NOT NULL AND current_club_id=club_id AND current_user_id=user_id
            AND ((role='REPRESENTATIVE' AND administrator_club_id IS NULL AND administrator_user_id IS NULL)
                OR (role='CLUB_ADMINISTRATOR' AND administrator_club_id IS NOT NULL AND administrator_user_id IS NOT NULL AND administrator_club_id=club_id AND administrator_user_id=user_id))))
);
CREATE INDEX idx_club_assignments_user ON club_role_assignments(user_id,revoked_at);
CREATE INDEX idx_club_assignments_club ON club_role_assignments(club_id,assignment_id);
CREATE TABLE club_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL REFERENCES clubs(club_id),
    actor_id BIGINT NOT NULL REFERENCES users(user_id),
    actor_assignment_id BIGINT REFERENCES club_role_assignments(assignment_id),
    target_assignment_id BIGINT NOT NULL REFERENCES club_role_assignments(assignment_id),
    action VARCHAR(50) NOT NULL CHECK (action IN ('CLUB_CREATED','ROLE_GRANTED','ROLE_REVOKED','ADMINISTRATOR_REPLACED')),
    reason VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_club_audit_club ON club_audit(club_id,audit_id);
