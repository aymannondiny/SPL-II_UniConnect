CREATE TABLE career_job_posts (
    job_post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_user_id BIGINT NOT NULL REFERENCES users(user_id),
    title VARCHAR(200) NOT NULL,
    company_name VARCHAR(200) NOT NULL,
    description VARCHAR(5000) NOT NULL,
    qualifications VARCHAR(5000) NOT NULL,
    location VARCHAR(200),
    employment_type VARCHAR(30) NOT NULL CHECK (employment_type IN ('INTERNSHIP','PART_TIME','FULL_TIME','CONTRACT')),
    work_mode VARCHAR(20) NOT NULL CHECK (work_mode IN ('ONSITE','REMOTE','HYBRID')),
    salary_range VARCHAR(200),
    application_url VARCHAR(2048),
    application_email VARCHAR(320),
    application_deadline DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PUBLISHED','CLOSED','REMOVED')),
    posted_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    closed_at TIMESTAMP,
    removed_at TIMESTAMP,
    author_redacted_at TIMESTAMP,
    CONSTRAINT career_post_channels CHECK (
        (author_redacted_at IS NULL AND (application_url IS NOT NULL OR application_email IS NOT NULL))
        OR (author_redacted_at IS NOT NULL AND application_url IS NULL AND application_email IS NULL)
    ),
    CONSTRAINT career_post_state CHECK (
        (status='PUBLISHED' AND closed_at IS NULL AND removed_at IS NULL)
        OR (status='CLOSED' AND closed_at IS NOT NULL AND removed_at IS NULL)
        OR (status='REMOVED' AND removed_at IS NOT NULL)
    )
);

CREATE INDEX idx_career_posts_active ON career_job_posts(status, application_deadline, posted_at, job_post_id);
CREATE INDEX idx_career_posts_author ON career_job_posts(author_user_id, posted_at, job_post_id);
CREATE INDEX idx_career_posts_filters ON career_job_posts(employment_type, work_mode, location);

CREATE TABLE career_job_skills (
    job_post_id BIGINT NOT NULL REFERENCES career_job_posts(job_post_id),
    skill_id BIGINT NOT NULL REFERENCES skills(skill_id),
    required BOOLEAN NOT NULL,
    PRIMARY KEY (job_post_id, skill_id)
);

CREATE INDEX idx_career_job_skills_skill ON career_job_skills(skill_id, job_post_id);

CREATE TABLE career_saved_jobs (
    saved_job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id BIGINT NOT NULL REFERENCES users(user_id),
    job_post_id BIGINT NOT NULL REFERENCES career_job_posts(job_post_id),
    note VARCHAR(1000),
    saved_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT unique_career_saved_job UNIQUE (student_user_id, job_post_id)
);

CREATE INDEX idx_career_saved_jobs_student ON career_saved_jobs(student_user_id, saved_at, saved_job_id);
